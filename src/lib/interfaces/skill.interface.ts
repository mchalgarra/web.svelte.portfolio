/**
 * Represents a skill data.
 */
export interface ISkill {
	/**
	 * The name of the skill.
	 *
	 * @example "JavaScript"
	 */
	name: string;

	/**
	 * The description of the skill.
	 *
	 * @example "JavaScript is a programming language that allows you to implement complex features on web pages."
	 */
	description: string;
}
